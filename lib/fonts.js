export const FONT_CATEGORIES = [...new Set(FONTS.map((font) => font.category))];

export const FONT_NAMES = FONTS.map((font) => font.name);

export const findFont = (name) => FONTS.find((font) => font.name === name) ?? FONTS[0];

/** A Google Fonts stylesheet URL for whole families (all their weights). */
export function fontsUrl(names) {
  const families = [...new Set(names)].map(findFont).map((font) =>
    `family=${font.name.replace(/ /g, "+")}${font.spec ? `:${font.spec}` : ""}`,
  );
  return `https://fonts.googleapis.com/css2?${families.join("&")}&display=swap`;
}

/** A tiny stylesheet with just the letters of every font's name, for the picker. */
export function previewFontsUrl() {
  const families = FONTS.map((font) => `family=${font.name.replace(/ /g, "+")}`).join("&");
  const letters = [...new Set(FONTS.map((font) => font.name).join(""))].join("");
  return `https://fonts.googleapis.com/css2?${families}&text=${encodeURIComponent(letters)}&display=swap`;
}
